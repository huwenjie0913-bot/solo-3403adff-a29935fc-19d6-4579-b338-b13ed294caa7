    kinds = {f["properties"]["feature"] for f in fc["features"]}
    assert {"survey_area", "no_fly_zone", "planned_segment", "track",
            "photo", "event", "home"} <= kinds
    statuses = {
        f["properties"]["status"] for f in fc["features"]
        if f["properties"]["feature"] == "planned_segment"
    }
    assert statuses == {"flown"}


