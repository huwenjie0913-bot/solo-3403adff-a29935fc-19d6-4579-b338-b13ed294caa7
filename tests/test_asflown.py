def test_reflight_locks_qualified_segments(client):
    plan = make_plan(client, no_fly_zones=[])
    ids = [s["id"] for s in plan["segments"]]
    flown = ids[: max(2, len(ids) // 3)]
    flight = verify(
        client, plan["plan_id"], synth_flight(plan, seg_ids=flown)
    ).get_json()

    resp = client.post(f"/api/v1/flights/{flight['flight_id']}/reflight", json={})
    assert resp.status_code == 201, resp.get_json()
    data = resp.get_json()
    assert data["parent_id"] == plan["plan_id"]
    # default lock = every segment the verification did not flag
    assert set(data["locked_segment_ids"]) == set(flown)
    assert data["metrics"]["num_frozen"] == len(flown)
    frozen = [s for s in data["segments"] if s["frozen"]]
    assert {s["id"] for s in frozen} == set(flown)
    # the reflight plan re-sweeps the missed area
    assert data["metrics"]["num_segments"] > len(flown)
    assert data["metrics"]["coverage_pct"] > 90.0

    cmp_resp = client.get(
        f"/api/v1/plans/{plan['plan_id']}/compare/{data['plan_id']}"
    )
    assert cmp_resp.status_code == 200


def test_reflight_warns_when_locking_flagged_segment(client):
    plan = make_plan(client, no_fly_zones=[])
    ids = [s["id"] for s in plan["segments"]]
    flown = ids[: max(2, len(ids) // 3)]
    flight = verify(
        client, plan["plan_id"], synth_flight(plan, seg_ids=flown)
    ).get_json()
    fid = flight["flight_id"]
    flagged = flight["refly_segments"][0]["id"]

    resp = client.post(
        f"/api/v1/flights/{fid}/reflight",
        json={"locked_segment_ids": flown + [flagged]},
    )
    assert resp.status_code == 201
    assert resp.get_json()["warnings"]

    resp = client.post(
        f"/api/v1/flights/{fid}/reflight",
        json={"locked_segment_ids": ["S999"]},
    )
    assert resp.status_code == 400
