def test_flight_is_stored_listed_and_replayed(client):
    plan = make_plan(client, no_fly_zones=[])
    created = verify(client, plan["plan_id"], synth_flight(plan)).get_json()
    fid = created["flight_id"]

    listing = client.get(f"/api/v1/plans/{plan['plan_id']}/flights").get_json()
    assert any(f["id"] == fid for f in listing["flights"])
    assert listing["flights"][0]["rules_version"]

    fetched = client.get(f"/api/v1/flights/{fid}")
    assert fetched.status_code == 200
    assert fetched.get_json()["metrics"] == created["metrics"]

    replay = client.post(f"/api/v1/flights/{fid}/replay")
    assert replay.status_code == 200
    data = replay.get_json()
    assert data["metrics_match"] is True
    assert data["events_match"] is True
    assert data["geojson_match"] is True
    assert data["stored_rules_version"] == data["current_rules_version"]


def test_flight_geojson_report(client):
    plan = make_plan(client)
    created = verify(client, plan["plan_id"], synth_flight(plan)).get_json()
