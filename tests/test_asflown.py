"""As-flown verification tests.

A synthetic sortie is generated by sampling the planned segments (track
points every ~15 m at the planned AMSL height, photos at the planned
exposure stations); individual tests then perturb the synthesis to
exercise deviation, gap, intrusion, margin and validation handling.
"""
import pytest

from drone_planner.app import create_app
from test_api import make_request

T0 = 1_700_000_000.0  # fixed epoch base keeps logs deterministic


@pytest.fixture()
def client(tmp_path):
    app = create_app(str(tmp_path / "test.db"))
    app.config.update(TESTING=True)
    return app.test_client()


def make_plan(client, **overrides):
    resp = client.post("/api/v1/plans", json=make_request(**overrides))
    assert resp.status_code == 201, resp.get_json()
    return resp.get_json()


def synth_flight(plan, *, seg_ids=None, lat_shift_deg=0.0, shift_seg_ids=None,
                 photo_alt_scale=None, battery_start=250.0, battery_end=180.0,
                 dt=5.0, drop_photo_ids=(), photo_id_prefix="IMG"):
    """Build an as-flown log following the plan's segments in flight order.

    ``lat_shift_deg`` moves the track/photos of ``shift_seg_ids`` (default:
    all chosen segments) north (the plan sweeps east-west lines with
    heading 0, so latitude is the cross-track direction).
    ``photo_alt_scale`` maps segment id -> AGL multiplier applied to that
    segment's photos only.
    """
    photo_alt_scale = photo_alt_scale or {}
    wanted = set(seg_ids) if seg_ids is not None else None
    if shift_seg_ids is None:
        shift_seg_ids = wanted if wanted is not None else {s["id"] for s in plan["segments"]}
    track, photos = [], []
    t = T0
    segs = [s for s in plan["segments"] if wanted is None or s["id"] in wanted]
    n_legs = sum(max(2, int(s["length_m"] // 15.0) + 1) for s in segs)
    leg_i = 0
    ph_i = 0
    for s in segs:
        (x0, y0), (x1, y1) = s["start"], s["end"]
        shift = lat_shift_deg if s["id"] in shift_seg_ids else 0.0
        n = max(2, int(s["length_m"] // 15.0) + 1)
        for k in range(n):
            f = k / (n - 1)
            frac = leg_i / max(1, n_legs - 1)
            track.append({
                "t": t,
                "pos": [x0 + (x1 - x0) * f, y0 + (y1 - y0) * f + shift],
                "alt_m": s["height_amsl_m"],
                "battery_wh": battery_start + (battery_end - battery_start) * frac,
            })
            t += dt
            leg_i += 1
        scale = photo_alt_scale.get(s["id"], 1.0)
        for k in range(s["photo_count"]):
            f = k / max(1, s["photo_count"] - 1)
            pid = f"{photo_id_prefix}_{ph_i:04d}"
            ph_i += 1
            if pid in drop_photo_ids:
                continue
            photos.append({
                "id": pid,
                "t": T0 + (t - T0) * 0.5 + k,  # inside the track time span
                "pos": [x0 + (x1 - x0) * f, y0 + (y1 - y0) * f + shift],
                "alt_m": s["height_amsl_m"] * scale,
                "attitude": {"roll_deg": 0.5, "pitch_deg": -0.4, "yaw_deg": 90.0},
            })
    photos.sort(key=lambda p: p["t"])
    return {"track": track, "photos": photos}


def verify(client, pid, flight, **extra):
    body = dict(flight)
    body.update(extra)
    return client.post(f"/api/v1/plans/{pid}/flights", json=body)


# --- happy path -------------------------------------------------------------

def test_clean_sortie_verifies(client):
    plan = make_plan(client, no_fly_zones=[])
    resp = verify(client, plan["plan_id"], synth_flight(plan))
    assert resp.status_code == 201, resp.get_json()
    data = resp.get_json()
    assert data["rules_version"]
    m = data["metrics"]
    assert m["coverage_pct"] > 95.0
    assert m["cross_track_max_m"] < 1.0
    assert m["exposure_gaps"] == 0
    assert m["nfz_intrusion_m"] == 0.0
    assert m["return_margin_ok"] is True
    assert m["gsd_breach_count"] == 0
    assert data["events"] == []
    assert data["first_event"] is None
    assert data["refly_segments"] == []
    assert data["uncovered_areas"] == []
    assert all(s["status"] == "flown" for s in data["segments"])
    # comparison against the plan
    cmp_ = data["comparison"]
    assert cmp_["coverage_pct"]["planned"] > 90.0
    assert abs(cmp_["coverage_pct"]["delta"]) < 5.0
    assert cmp_["energy_wh"]["actual"] == pytest.approx(250.0 - 180.0, abs=0.01)
    assert cmp_["photo_count"]["actual"] == m["photo_count"]
    assert cmp_["risk"]["actual"]["cross_track_deviations"] == 0


def test_gsd_and_spacing_reflect_terrain(client):
    plan = make_plan(client, no_fly_zones=[])
