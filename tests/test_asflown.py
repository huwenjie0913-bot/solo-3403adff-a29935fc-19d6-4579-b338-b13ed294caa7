# --- validation --------------------------------------------------------------

def test_track_time_order_and_missing_data_rejected(client):
    plan = make_plan(client, no_fly_zones=[])
    flight = synth_flight(plan)
    pid = plan["plan_id"]

    swapped = dict(flight)
    swapped["track"] = [dict(p) for p in flight["track"]]
    swapped["track"][5], swapped["track"][6] = swapped["track"][6], swapped["track"][5]
    resp = verify(client, pid, swapped)
    assert resp.status_code == 400
    assert any("time order" in e or "increasing" in e for e in resp.get_json()["errors"])

    nulled = dict(flight)
    nulled["track"] = [dict(p) for p in flight["track"]]
    nulled["track"][3]["alt_m"] = None
    resp = verify(client, pid, nulled)
    assert resp.status_code == 400
    assert any("track[3].alt_m" in e for e in resp.get_json()["errors"])

    missing_att = dict(flight)
    missing_att["photos"] = [dict(p) for p in flight["photos"]]
    del missing_att["photos"][0]["attitude"]
    resp = verify(client, pid, missing_att)
    assert resp.status_code == 400
    assert any("attitude" in e for e in resp.get_json()["errors"])


def test_unit_checks(client):
    plan = make_plan(client, no_fly_zones=[])
    flight = synth_flight(plan)
    pid = plan["plan_id"]

    # battery in percent instead of Wh
    pct = dict(flight)
    pct["track"] = [dict(p, battery_wh=95.0) for p in flight["track"]]
    resp = verify(client, pid, pct)
    assert resp.status_code == 201  # 95 Wh is plausible; monotonic ok
    # battery far above the nominal pack -> unit error
    over = dict(flight)
    over["track"] = [dict(p, battery_wh=9999.0) for p in flight["track"]]
    resp = verify(client, pid, over)
    assert resp.status_code == 400
    assert any("battery_wh" in e for e in resp.get_json()["errors"])

    # altitude a hundredfold off (e.g. centimetres) -> outside the AMSL range
    hundredfold = dict(flight)
    hundredfold["track"] = [dict(p, alt_m=p["alt_m"] * 100.0) for p in flight["track"]]
    resp = verify(client, pid, hundredfold)
    assert resp.status_code == 400
    assert any("alt_m" in e for e in resp.get_json()["errors"])

    # AGL submitted as AMSL -> far below the hill terrain (datum confusion)
    agl_only = dict(flight)
    agl_only["track"] = [dict(p, alt_m=109.44) for p in flight["track"]]
    resp = verify(client, pid, agl_only)
    assert resp.status_code == 400
    assert any("below terrain" in e for e in resp.get_json()["errors"])

    # timestamps in 100 ms units -> implied speed far too high
    fast = dict(flight)
    fast["track"] = [dict(p, t=T0 + i * 0.1) for i, p in enumerate(flight["track"])]
    fast["photos"] = []  # keep trigger times out of the way of the speed check
    resp = verify(client, pid, fast)
    assert resp.status_code == 400
    assert any("implied speed" in e for e in resp.get_json()["errors"])

    # battery increasing mid-flight
    up = dict(flight)
    up["track"] = [dict(p) for p in flight["track"]]
    up["track"][10]["battery_wh"] = up["track"][0]["battery_wh"] + 5.0
    resp = verify(client, pid, up)
    assert resp.status_code == 400
    assert any("battery_wh" in e for e in resp.get_json()["errors"])


def test_crs_and_structure_validation(client):
    plan = make_plan(client, no_fly_zones=[])
    flight = synth_flight(plan)
    pid = plan["plan_id"]

    assert verify(client, pid, flight, crs="EPSG:foo").status_code == 400
    assert verify(client, pid, {"track": [], "photos": []}).status_code == 400
    assert verify(client, pid, {"photos": []}).status_code == 400
    assert verify(client, pid, {"track": flight["track"]}).status_code == 400

    # flight log in UTM 50N while the plan is in EPSG:4326
    from pyproj import Transformer
    fwd = Transformer.from_crs("EPSG:4326", "EPSG:32650", always_xy=True)
    utm = {
        "crs": "EPSG:32650",
        "track": [dict(p, pos=list(fwd.transform(*p["pos"]))) for p in flight["track"]],
        "photos": [dict(p, pos=list(fwd.transform(*p["pos"]))) for p in flight["photos"]],
    }
    resp = verify(client, pid, utm)
    assert resp.status_code == 201, resp.get_json()
    assert resp.get_json()["metrics"]["cross_track_max_m"] < 1.0


